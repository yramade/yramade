#include <stdio.h>
#include <stdlib.h>
#include <time.h>

void main() {
  int a = 99;
  int b = 2;

  printf(" a + b : %d\n", a + b);
  printf(" a - b : %d\n", a - b);
  printf(" a * b : %d\n", a * b);
  printf(" a / b : %d\n", a / b);
  printf(" a %% b : %d\n", a % b);
  printf(" -a : %d\n", -a);

  return;
}